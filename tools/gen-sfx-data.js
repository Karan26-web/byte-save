#!/usr/bin/env node
/* ============================================================================
   DEV-ONLY: regenerate sfx-data.js from the optimised Ogg/Opus one-shots.
   node tools/gen-sfx-data.js
   ----------------------------------------------------------------------------
   script.js decodes these two SFX once into AudioBuffers so the cover-flip and
   page-flip sounds are sample-accurate with zero start latency. They are inlined
   as base64 data URIs because file:// blocks fetch() of a plain path — and
   decodeAudioData needs the raw bytes.
   Re-run this after re-encoding either sfx/*.ogg file.
   ============================================================================ */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const read = (rel) => fs.readFileSync(path.join(ROOT, rel)).toString("base64");

const cover = read("sfx/cover page flip.ogg");
const flip = read("sfx/Page flip.ogg");

const out = `// Auto-generated by tools/gen-sfx-data.js — do NOT hand-edit.
// The two one-shot SFX inlined as base64 data URIs so they can be fetched + decoded by
// the Web Audio API even when the page is opened via file:// (where fetch/XHR of a plain
// file path is blocked). Used by script.js for glitch-free, zero-latency cover-flip /
// page-flip sounds. BG music stays a normal <audio> (long ambient loop; start latency
// does not matter there).
// Source files are the OPTIMISED Ogg/Opus versions (sfx/*.ogg) — Opus in an Ogg container
// is decoded by AudioContext.decodeAudioData in Chrome, Edge, Firefox and Safari 15+.
window.SFX_DATA = {
  cover: "data:audio/ogg;base64,${cover}",
  flip: "data:audio/ogg;base64,${flip}"
};
`;
fs.writeFileSync(path.join(ROOT, "sfx-data.js"), out);
console.log(`sfx-data.js regenerated — ${(out.length / 1024).toFixed(1)} KB`);
