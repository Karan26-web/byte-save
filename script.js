/* STAGE B — starts only AFTER the flipbook's own load event, during idle time, so it
   can never compete with Stage A or delay the Start button:
     • preload.js warms the remaining bytes (later videos, both games' assets);
     • warmLbd() boots the upcoming game into the hidden iframe so landing on its
       page shows a live intro instantly, with no spinner and no second loading screen.
   Both games are silent until their own Play button is tapped, so booting one hidden
   leaks no audio. */
window.addEventListener("load", function () {
  if (window.FlipbookPreload) window.FlipbookPreload.startStageB();
  // Give Stage B's prioritised queue (theme music, then the story videos in page order)
  // a short head start before booting the game. LBD 1's own audio.init() creates ~21
  // Audio objects with preload="auto", so booting it the same instant would put its
  // whole VO pack in front of the clip that plays on page 1. The learner cannot reach
  // a game page in under ~2 minutes of story video, so this costs nothing.
  setTimeout(warmLbd, 2000);
});

